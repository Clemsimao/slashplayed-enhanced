#!/usr/bin/env python3
"""Phase 2: emit C that imports every symbol the client imports, from the same library.

Usage: gen_refs.py <imports.json> <client binary> <out.c>

Each import becomes an asm-labelled extern whose address goes into sp_refs[], so dyld binds all of
them at launch (non-lazily) just as it does the client's. The client's weak imports stay weak.
Only symbol names come from the client; no code or data.
"""
import json
import re
import subprocess
import sys


def main():
    imports_json, client, out = sys.argv[1:]
    records = [r for r in json.load(open(imports_json)) if r["kind"] != "absent"]  # dyld_stub_binder
    fixups = subprocess.run(["dyld_info", "-fixups", client], capture_output=True, text=True,
                            check=True).stdout
    weak = set(re.findall(r"\S+/(\S+) \[weak-import\]", fixups))

    lines = ["// Generated by research/loadertest/gen_refs.py. Don't edit.", "#include <stddef.h>", ""]
    for i, r in enumerate(records):
        attr = " __attribute__((weak_import))" if r["symbol"] in weak else ""
        lines.append(f'extern char sp_ref{i} __asm__("{r["symbol"]}"){attr};')
    lines += ["", "const void *const sp_refs[] = {"]
    lines += [f"    &sp_ref{i}," for i in range(len(records))]
    lines += ["};", "const char *const sp_ref_names[] = {"]
    lines += [f'    "{r["from"]}/{r["symbol"]}",' for r in records]
    lines += ["};", f"const size_t sp_ref_count = {len(records)};", ""]
    open(out, "w").write("\n".join(lines))
    print(f"{len(records)} refs ({len(weak)} weak) -> {out}")


if __name__ == "__main__":
    main()
